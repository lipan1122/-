/**
 * 演示数据开关（整改清单 P1-23）
 *
 * ── 为什么单独一个文件 ──
 * 渠道页 / 渠道订单页各有一处「演示 / 生成示例数据」的按钮，它们会往**生产库**写
 * 随机渠道订单（随机客人、随机手机号、随机房型）并自动建正式预订。
 * 真实的酒店管理员点一下，库里就多出一批永远不会有人来住的订单，
 * 连带污染房量口径、渠道对账、夜审收入统计。
 *
 * 项目里已有约定：其它模块（AR / 商品 / 积分 / 收银）灌演示数据前都检查
 * `process.env.PMS_DEMO_SEED === "1"`，默认不灌。渠道模块此前没跟上，
 * 这里补同一个开关，让「演示数据的产生」只有一个入口、一个判据。
 *
 * 注意：
 *   · 判据只看环境变量，**不看页面参数** —— 否则构造一个请求就能在生产库造数；
 *   · 关闭时不是静默 return，而是回一句明确的中文提示（否则用户只会觉得按钮坏了）；
 *   · 生产环境不要设 PMS_DEMO_SEED=1（DEPLOY 文档里已有这条约定）。
 */

/** 演示数据是否开启（只有显式 PMS_DEMO_SEED=1 才算开启） */
export function demoSeedEnabled(): boolean {
  return process.env.PMS_DEMO_SEED === "1";
}

/** 关闭时的统一提示语（页面 / action 共用，避免文案漂移） */
export const DEMO_SEED_DISABLED_MESSAGE =
  "演示数据功能已关闭（默认不写入生产库）。如需演示数据，请在服务端设置环境变量 PMS_DEMO_SEED=1 后重启";
